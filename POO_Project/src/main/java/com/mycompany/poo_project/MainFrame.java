    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        if(jTabbedPane1.getSelectedIndex() == 0){
            try {
                FileWriter fw = new FileWriter("vectorAlarma.txt");
                    for (Gadgets g : listaFiltAlarma) {
                    fw.write(g + "\n");
                    }
                fw.close();
                System.out.println("Vector alarma salvat!");
                
            }catch (IOException e){
                  e.printStackTrace();
            }
        }else if(jTabbedPane1.getSelectedIndex() == 1){
            try {
                FileWriter fw = new FileWriter("vectorPriza.txt");
                    for (Gadgets g : listaFiltPriza) {
                    fw.write(g + "\n");
                    }
                fw.close();
                System.out.println("Vector priza salvat!");
                
            }catch (IOException e){
                  e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jButton3ActionPerformed

