    public Alarma parseAlarma(String linie) {
        String[] parts = linie.split(" ");

        String model = parts[1];
        String detector = parts[3];
        String conexiune = parts[5];
        String montaj = parts[7];
        int greutate = Integer.parseInt(parts[9]);
        String dim = parts[11];

        return new Alarma(model, "Alb", false, "Dahua", detector, conexiune, montaj, greutate, dim, 350);
}


