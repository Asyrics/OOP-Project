    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        lista.clear();
        for(Gadgets a : listaAlarma){
                if(a instanceof Alarma){
                    Alarma a1 = (Alarma) a;
                    if(a1.getTipDet().equalsIgnoreCase(jTextField1.getText()) && a1.getBrand().equalsIgnoreCase(jTextField2.getText())){
                        lista.addElement(a1);
                        listaFiltAlarma.add(a1);
                    }
                }
        }
        jTextField1.setText("Cond A1");
        jTextField2.setText("Cond A2");
    }//GEN-LAST:event_jButton1MouseClicked

    private void jButton2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton2MouseClicked
        lista.clear();
        for(Gadgets a : listaPriza){
                if(a instanceof PrizaSmart){
                    PrizaSmart p1 = (PrizaSmart) a;
                    if(p1.getNrPrize() == Integer.parseInt(jTextField3.getText()) && p1.getBrand().equalsIgnoreCase(jTextField4.getText())){
                        lista.addElement(p1);
                        listaFiltPriza.add(p1);
                    }
                }
        }
        jTextField1.setText("Cond P1");
        jTextField2.setText("Cond P2");
    }//GEN-LAST:event_jButton2MouseClicked

